CREATE TABLE IF NOT EXISTS `Account` (
  `AccountID` int NOT NULL AUTO_INCREMENT,
  `Email` varchar(256) COLLATE utf8mb4_0900_as_ci NOT NULL,
  `PasswordHash` varchar(255) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `GoogleSubjectId` varchar(100) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `FullName` varchar(150) COLLATE utf8mb4_0900_as_ci NOT NULL,
  `AvatarUrl` varchar(500) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `DateOfBirth` date DEFAULT NULL,
  `Phone` varchar(20) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `SocialLinks` varchar(500) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `Role` varchar(20) COLLATE utf8mb4_0900_as_ci NOT NULL DEFAULT 'PLAYER',
  `Status` varchar(20) COLLATE utf8mb4_0900_as_ci NOT NULL DEFAULT 'PENDING_VERIFY',
  `BanReason` varchar(500) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `NotifyInApp` tinyint(1) NOT NULL DEFAULT '1',
  `NotifyEmail` tinyint(1) NOT NULL DEFAULT '1',
  `OrganizerRequestStatus` varchar(20) COLLATE utf8mb4_0900_as_ci NOT NULL DEFAULT 'NONE',
  `OrganizerRequestedAt` datetime DEFAULT NULL,
  `OrganizerRequestNote` varchar(1000) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `OrganizerRequestEmail` varchar(254) COLLATE utf8mb4_0900_as_ci DEFAULT NULL,
  `EmailVerifiedAt` datetime DEFAULT NULL,
  `CreatedAt` datetime NOT NULL DEFAULT (utc_timestamp()),
  PRIMARY KEY (`AccountID`),
  UNIQUE KEY `UQ_Account_Email` (`Email`),
  UNIQUE KEY `UX_Account_Google` (`GoogleSubjectId`),
  CONSTRAINT `CK_Account_Login` CHECK (((`PasswordHash` is not null) or (`GoogleSubjectId` is not null))),
  CONSTRAINT `CK_Account_OrgReq` CHECK ((`OrganizerRequestStatus` in (_utf8mb4'NONE',_utf8mb4'PENDING',_utf8mb4'APPROVED',_utf8mb4'REJECTED'))),
  CONSTRAINT `CK_Account_OrgReqAt` CHECK (((`OrganizerRequestStatus` = _utf8mb4'NONE') or (`OrganizerRequestedAt` is not null))),
  CONSTRAINT `CK_Account_Role` CHECK ((`Role` in (_utf8mb4'PLAYER',_utf8mb4'ORGANIZER',_utf8mb4'ADMIN'))),
  CONSTRAINT `CK_Account_Status` CHECK ((`Status` in (_utf8mb4'PENDING_VERIFY',_utf8mb4'ACTIVE',_utf8mb4'BANNED')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

